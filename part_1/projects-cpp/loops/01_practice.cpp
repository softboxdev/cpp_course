#include <iostream>
using namespace std;

int main() {
    // Создаем массив из 5 целых чисел
    int arr[5] = {42, 15, 8, 63, 19};
    
    // Инициализируем переменные для хранения минимума и максимума
    // Начинаем с первого элемента массива
    int min = arr[0];
    int max = arr[0];
    
    // Перебираем все элементы массива, начиная со второго (индекс 1)
    for(int i = 1; i < 5; i++) {
        // Если текущий элемент меньше текущего минимума
        if(arr[i] < min) {
            min = arr[i]; // обновляем значение минимума
        }
        
        // Если текущий элемент больше текущего максимума
        if(arr[i] > max) {
            max = arr[i]; // обновляем значение максимума
        }
    }
    
    // Выводим результаты
    cout << "Массив: ";
    for(int i = 0; i < 5; i++) {
        cout << arr[i] << " ";
    }
    cout << endl;
    
    cout << "Минимальный элемент: " << min << endl;
    cout << "Максимальный элемент: " << max << endl;
    
    return 0;
}