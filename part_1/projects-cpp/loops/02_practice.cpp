#include <iostream>
using namespace std;

int main() {
    // Исходный неотсортированный массив
    int arr[6] = {64, 34, 25, 12, 22, 11};
    
    cout << "Исходный массив: ";
    for(int i = 0; i < 6; i++) {
        cout << arr[i] << " ";
    }
    cout << endl;
    
    // Внешний цикл: проходим по массиву (n-1) раз
    // Каждый проход "всплывает" самый большой элемент в конец
    for(int i = 0; i < 5; i++) { // 5 = 6-1 (длина массива - 1)
        
        // Внутренний цикл: сравниваем соседние элементы
        // После каждого прохода внешнего цикла самый большой элемент
        // уже находится на своем месте, поэтому проверяем на 1 элемент меньше
        for(int j = 0; j < 5 - i; j++) {
            
            // Если текущий элемент больше следующего
            if(arr[j] > arr[j + 1]) {
                // Меняем их местами
                int temp = arr[j];     // Сохраняем текущий элемент во временной переменной
                arr[j] = arr[j + 1];   // На место текущего ставим следующий
                arr[j + 1] = temp;     // На место следующего ставим сохраненный текущий
            }
        }
        
        // Можно вывести промежуточное состояние массива после каждого прохода
        cout << "После прохода " << i + 1 << ": ";
        for(int k = 0; k < 6; k++) {
            cout << arr[k] << " ";
        }
        cout << endl;
    }
    
    cout << "Отсортированный массив: ";
    for(int i = 0; i < 6; i++) {
        cout << arr[i] << " ";
    }
    cout << endl;
    
    return 0;
}