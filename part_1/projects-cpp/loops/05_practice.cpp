#include <iostream>
using namespace std;

int main() {
    // Создаем массив и определяем его размер
    int arr[] = {1, 2, 3, 4, 5, 6, 7};
    int size = 7;  // размер массива
    
    cout << "Исходный массив: ";
    for(int i = 0; i < size; i++) {
        cout << arr[i] << " ";
    }
    cout << endl;
    
    // Алгоритм обращения массива:
    // Меняем местами первый с последним, второй с предпоследним и т.д.
    // Идем только до середины массива, иначе вернемся к исходному порядку
    for(int i = 0; i < size / 2; i++) {
        // Сохраняем значение левого элемента
        int temp = arr[i];
        // Заменяем левый элемент правым
        arr[i] = arr[size - 1 - i];
        // Заменяем правый элемент сохраненным левым
        arr[size - 1 - i] = temp;
        
        // size - 1 - i - это индекс элемента с конца:
        // size - 1 - последний элемент
        // size - 1 - i - элемент, отстоящий на i позиций от конца
    }
    
    cout << "Перевернутый массив: ";
    for(int i = 0; i < size; i++) {
        cout << arr[i] << " ";
    }
    cout << endl;
    
    return 0;
}